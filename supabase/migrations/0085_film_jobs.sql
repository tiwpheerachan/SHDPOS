  ('E',40,'E40','70mai essential-35%'),('E',60,'E60','70mai essential-15%'),('E',80,'E80','70mai essential-5%'),
  ('P',40,'P40','70mai pro-35%'),('P',60,'P60','70mai pro-15%'),('P',80,'P80','70mai pro-8%'),
  ('U',40,'U40','70mai ultra-35%'),('U',60,'U60','70mai ultra-13%')
) v(s, shade, m, sku)
on conflict (series_code, shade) do nothing;

