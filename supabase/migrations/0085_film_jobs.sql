-- ความเข้ม → ม้วนฟิล์มที่ตัดสต๊อก (feet_per_unit: 1 ชิ้นในสต๊อก = กี่ฟุต)
create table if not exists film_shades (
  series_code text not null references film_series(code) on delete cascade,
  shade int not null check (shade between 1 and 99),
  model_code text not null,                       -- E40, P80 ...
  stock_product_id uuid references products(id),
  feet_per_unit numeric(8,2) not null default 1 check (feet_per_unit > 0),
  active boolean not null default true,
  primary key (series_code, shade)
);

-- ราคา: position_code 'ALL' = รอบคัน · รายตำแหน่ง = FW/RW/FSW/RSW (ว่าง = ยังขายแยกไม่ได้)
create table if not exists film_prices (
  series_code text not null references film_series(code) on delete cascade,
  size_code text not null references film_sizes(code) on delete cascade,
  position_code text not null default 'ALL',
  price numeric(12,2) not null check (price > 0),
  primary key (series_code, size_code, position_code)
);

-- รุ่นรถ → ขนาด (ค้นหาที่หน้าร้าน)
create table if not exists film_car_models (
  id uuid primary key default gen_random_uuid(),
  make text not null, model text not null,
  size_code text not null references film_sizes(code),
  created_at timestamptz not null default now()
);
create unique index if not exists film_car_models_uq on film_car_models (lower(make), lower(model));

