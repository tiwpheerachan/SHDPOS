-- 0085 งานติดฟิล์มรถยนต์ (70mai film)
--   เลือกขนาดรถ (หรือรุ่นรถ → ขนาด) → รุ่นฟิล์ม (Essential/Pro/Ultra) → ตำแหน่ง + ความเข้ม
--   ราคา = ตาราง film_prices (รอบคัน 'ALL' หรือรายตำแหน่ง) · ตัดสต๊อก = ม้วนฟิล์มตามความเข้ม หน่วยฟุต (1 ชิ้น = 1 ฟุต ตั้งได้)
