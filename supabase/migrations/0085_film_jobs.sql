-- ม้วนฟิล์ม Pro / Ultra (ยังไม่มีในระบบ) — 1 ชิ้น = 1 ฟุต
insert into products (sku, brand_id, name_th, name_en, unit, price, kind, is_active, is_stocked, track_serial, serial_policy_confirmed, kind_policy_confirmed, is_discountable, warranty_months)
select v.sku, (select id from brands where name = '70mai' limit 1), v.name, v.name, 'ฟุต', 0, 'goods', true, true, false, true, true, false, 84
from (values
  ('70mai pro-8%',   '70 maifilm Pro VLT8% (ม้วน 60"×100ft)'),
  ('70mai pro-15%',  '70 maifilm Pro VLT15% (ม้วน 60"×100ft)'),
  ('70mai pro-35%',  '70 maifilm Pro VLT35% (ม้วน 60"×100ft)'),
  ('70mai ultra-13%','70 maifilm Ultra VLT13% (ม้วน 60"×100ft)'),
  ('70mai ultra-35%','70 maifilm Ultra VLT35% (ม้วน 60"×100ft)')
) v(sku, name)
where not exists (select 1 from products p where p.sku = v.sku);

-- ม้วน Essential (มีอยู่แล้วจากคลังกลาง) → เปิดใช้งานเพื่อขายผ่านงานติดฟิล์ม (ราคาสินค้า 0 — ราคามาจาก film_prices ไม่ขายเดี่ยว)
update products set is_active = true, serial_policy_confirmed = true, kind_policy_confirmed = true, track_serial = false, updated_at = now()
where sku in ('70mai essential-5%', '70mai essential-15%', '70mai essential-35%');

-- ความเข้มตามชีท: Essential 40/60/80 → VLT35/15/5 · Pro 40/60/80 → VLT35/15/8 · Ultra 40/60 → VLT35/13
