-- พื้นที่ต่อตำแหน่ง (ตร.ฟุต) ตามขนาดรถ
create table if not exists film_size_areas (
  size_code text not null references film_sizes(code) on delete cascade,
  position_code text not null references film_positions(code) on delete cascade,
  sqft numeric(8,2) not null check (sqft > 0),
  primary key (size_code, position_code)
);

create table if not exists film_series (
  code text primary key, name text not null, tagline_th text, tagline_en text, tagline_zh text, sort int not null default 0, active boolean not null default true
