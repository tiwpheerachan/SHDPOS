--   ข้อมูลตั้งต้นจากชีท "Film Competitor / extra"
-- =====================================================================

-- เงื่อนไขการขาย (แถวเดียว)
create table if not exists film_config (
  id                  int primary key default 1 check (id = 1),
  one_series_per_car  boolean not null default true,   -- รุ่นฟิล์มเดียวทั้งคัน
  full_car_only       boolean not null default true,   -- ขายเฉพาะรอบคัน (ปิด = ขายรายตำแหน่งได้ ถ้ามีราคา)
  mixed_shades        boolean not null default true,   -- ความเข้มต่างกันได้ในแต่ละตำแหน่ง
  roll_width_ft       numeric(6,2) not null default 5, -- ม้วนกว้าง 60 นิ้ว
  round_up_feet       boolean not null default true,   -- ปัดฟุตขึ้นเป็นจำนวนเต็มต่อม้วน (JST รับจำนวนเต็ม)
  brand_id            uuid references brands(id),
  updated_by          uuid,
  updated_at          timestamptz not null default now()
);
insert into film_config(id, brand_id) select 1, (select id from brands where name = '70mai' limit 1) on conflict (id) do nothing;

